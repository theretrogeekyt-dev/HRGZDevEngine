//
// Find string width from hu_font chars
//
int M_StringWidth(char* string)
{
    int             i;
    int             w = 0;
    int             c;
	
    for (i = 0;i < strlen(string);i++)
    {
	c = toupper(string[i]) - HU_FONTSTART;
	if (c < 0 || c >= HU_FONTSIZE)
	    w += 4;
	else
	    w += SHORT (hu_font[c]->width);
    }
		
    return w;
}



//
//      Find string height from hu_font chars
//
int M_StringHeight(char* string)
{
    int             i;
    int             h;
    int             height = SHORT(hu_font[0]->height);
	
    h = height;
    for (i = 0;i < strlen(string);i++)
	if (string[i] == '\n')
	    h += height;
		
    return h;
}


//
//      Write a string using the hu_font
//
void
M_WriteText
( int		x,
  int		y,
  char*		string)
{
    int		w;
    char*	ch;
    int		c;
    int		cx;
    int		cy;
		

    ch = string;
    cx = x;
    cy = y;
	
    while(1)
    {
	c = *ch++;
	if (!c)
	    break;
	if (c == '\n')
	{
	    cx = x;
	    cy += 12;
	    continue;
	}
		
	c = toupper(c) - HU_FONTSTART;
	if (c < 0 || c>= HU_FONTSIZE)
	{
	    cx += 4;
	    continue;
	}
		
	w = SHORT (hu_font[c]->width);
	if (cx+w > SCREENWIDTH)
	    break;
	V_DrawPatchDirect(cx, cy, 0, hu_font[c]);
	cx+=w;
    }
}


//
// M_MenuStringWidth
// Returns the pixel width of a string rendered with M_DrawMenuText.
//
int M_MenuStringWidth(char* string)
{
    int		w;
    char*	ch;
    int		c;

    if (!string)
	return 0;

    w = 0;
    ch = string;
    while (*ch)
    {
	c = *ch++;
	if (c == ' ')
	{
	    w += 6;
	    continue;
	}
	c = toupper(c) - HU_FONTSTART;
	if (c < 0 || c >= HU_FONTSIZE || !hu_font[c])
	{
	    w += 6;
	    continue;
	}
	w += SHORT(hu_font[c]->width) + 1;
    }
    return (w > 0) ? (w - 1) : 0;
}


//
// M_DrawMenuText
// Draws DOOM-style menu text using hu_font glyphs scaled 2x vertically (14-15px)
// with a 1px drop shadow in dark crimson (color 45), matching official patch aesthetics.
//
void M_DrawMenuText(int x, int y, char* string)
{
    char*	ch;
    int		c;
    int		cx;
    int		col;
    int		w;
    int		r;
    int		py1, py2;
    int		px;
    int		mark_w;
    patch_t*	patch;
    column_t*	column;
    byte*	source;
    byte*	scr = screens[0];

    if (!scr || !string)
	return;

    // Pass 1: Drop Shadow (palette index 45, offset +1x, +1y)
    cx = x;
    ch = string;
    while (*ch)
    {
	c = *ch++;
	if (c == ' ')
	{
	    cx += 6;
	    continue;
	}
	c = toupper(c) - HU_FONTSTART;
	if (c < 0 || c >= HU_FONTSIZE || !hu_font[c])
	{
	    cx += 6;
	    continue;
	}

	patch = hu_font[c];
	w = SHORT(patch->width);
	if (cx + w + 1 >= SCREENWIDTH)
	    break;

	for (col = 0; col < w; col++)
	{
	    px = cx + col + 1;
	    if (px < 0 || px >= SCREENWIDTH)
		continue;

	    column = (column_t *)((byte *)patch + LONG(patch->columnofs[col]));
	    while (column->topdelta != 0xff)
	    {
		for (r = 0; r < column->length; r++)
		{
		    py1 = y + (column->topdelta + r) * 2 + 1;
		    py2 = py1 + 1;
		    if (py1 >= 0 && py1 < SCREENHEIGHT)
			scr[py1 * SCREENWIDTH + px] = 45;
		    if (py2 >= 0 && py2 < SCREENHEIGHT)
			scr[py2 * SCREENWIDTH + px] = 45;
		}
		column = (column_t *)((byte *)column + column->length + 4);
	    }
	}
	cx += w + 1;
    }

    // Pass 2: Foreground (original pixel colors from font patch, scaled 2x vertically)
    cx = x;
    ch = string;
    while (*ch)
    {
	c = *ch++;
	if (c == ' ')
	{
	    cx += 6;
	    continue;
	}
	c = toupper(c) - HU_FONTSTART;
	if (c < 0 || c >= HU_FONTSIZE || !hu_font[c])
	{
	    cx += 6;
	    continue;
	}

	patch = hu_font[c];
	w = SHORT(patch->width);
	if (cx + w + 1 >= SCREENWIDTH)
	    break;

	for (col = 0; col < w; col++)
	{
	    px = cx + col;
	    if (px < 0 || px >= SCREENWIDTH)
		continue;

	    column = (column_t *)((byte *)patch + LONG(patch->columnofs[col]));
	    while (column->topdelta != 0xff)
	    {
		source = (byte *)column + 3;
		for (r = 0; r < column->length; r++)
		{
		    py1 = y + (column->topdelta + r) * 2;
		    py2 = py1 + 1;
		    if (py1 >= 0 && py1 < SCREENHEIGHT)
			scr[py1 * SCREENWIDTH + px] = source[r];
		    if (py2 >= 0 && py2 < SCREENHEIGHT)
			scr[py2 * SCREENWIDTH + px] = source[r];
		}
		column = (column_t *)((byte *)column + column->length + 4);
	    }
	}
	cx += w + 1;
    }

    mark_w = cx - x + 2;
    if (x + mark_w > SCREENWIDTH)
	mark_w = SCREENWIDTH - x;
    if (mark_w > 0 && y >= 0 && y + 16 <= SCREENHEIGHT)
	V_MarkRect(x, y, mark_w, 16);
}



