//
// M_Drawer
// Called after the view has been rendered,
// but before it has been blitted.
//
void M_Drawer (void)
{
    static short	x;
    static short	y;
    short		i;
    short		max;
    char		string[40];
    int			start;

    inhelpscreens = false;

    // Lobby screens override standard menu drawing
    if (I_Net_GetState() == NET_STATE_HOST_LOBBY)
    {
        M_DrawHostLobby();
        return;
    }
    if (I_Net_GetState() == NET_STATE_CLIENT_LOBBY)
    {
        M_DrawClientLobby();
        return;
    }

    // Horiz. & Vertically center string and print it.
    if (messageToPrint)
    {
	start = 0;
	y = 100 - M_StringHeight(messageString)/2;
	while(*(messageString+start))
	{
	    for (i = 0;i < strlen(messageString+start);i++)
		if (*(messageString+start+i) == '\n')
		{
		    memset(string,0,40);
		    strncpy(string,messageString+start,i);
		    start += i+1;
		    break;
		}
				
	    if (i == strlen(messageString+start))
	    {
		strcpy(string,messageString+start);
		start += i;
	    }
				
	    x = SCREENWIDTH / 2 - M_StringWidth(string)/2;
	    M_WriteText(x,y,string);
	    y += SHORT(hu_font[0]->height);
	}
	return;
    }

    if (!menuactive)
	return;

    if (currentMenu->routine)
	currentMenu->routine();         // call Draw routine
    
    // DRAW MENU
    x = currentMenu->x;
    y = currentMenu->y;
    max = currentMenu->numitems;

    for (i=0;i<max;i++)
    {
	if (currentMenu->menuitems[i].name[0])
	{
	    if (strcmp(currentMenu->menuitems[i].name, "M_MULTI") == 0)
	    {
		V_DrawPatchDirect (x, y, 0, (patch_t*)m_multi_patch);
	    }
	    else if (strcmp(currentMenu->menuitems[i].name, "M_HOSTG") == 0)
	    {
		V_DrawPatchDirect (x, y, 0, (patch_t*)m_host_patch);
	    }
	    else if (strcmp(currentMenu->menuitems[i].name, "M_JOING") == 0)
	    {
		V_DrawPatchDirect (x + 1, y, 0, (patch_t*)m_join_patch);
	    }
	    else if (strncmp(currentMenu->menuitems[i].name, "M_", 2) == 0 &&
	        W_CheckNumForName(currentMenu->menuitems[i].name) >= 0)
	    {
		V_DrawPatchDirect (x,y,0,
				   W_CacheLumpName(currentMenu->menuitems[i].name ,PU_CACHE));
	    }
	    else
	    {
		M_DrawMenuText (x, y, currentMenu->menuitems[i].name);
	    }
	}
	y += LINEHEIGHT;
    }

    
    // DRAW SKULL
    V_DrawPatchDirect(x + SKULLXOFF,currentMenu->y - 5 + itemOn*LINEHEIGHT, 0,
		      W_CacheLumpName(skullName[whichSkull],PU_CACHE));

}


