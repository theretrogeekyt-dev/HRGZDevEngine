//
// M_Ticker
//
void M_Ticker (void)
{
    if (--skullAnimCounter <= 0)
    {
	whichSkull ^= 1;
	skullAnimCounter = 8;
    }

    net_state_t net_st = I_Net_GetState();
    if (net_st == NET_STATE_HOST_LOBBY)
    {
        I_Net_HostLobbyTicker();
    }
    else if (net_st == NET_STATE_CLIENT_LOBBY)
    {
        if (I_Net_ClientLobbyTicker())
        {
            usergame = true;
            demoplayback = false;
            advancedemo = false;
            D_CheckNetGame();
            G_InitNew(startskill, startepisode, startmap);
            M_ClearMenus();
        }
    }
}


//
// M_Init
//
void M_Init (void)
{
    currentMenu = &MainDef;
    menuactive = 0;
    itemOn = currentMenu->lastOn;
    whichSkull = 0;
    skullAnimCounter = 10;
    screenSize = screenblocks - 3;
    messageToPrint = 0;
    messageString = NULL;
    messageLastMenuActive = menuactive;
    quickSaveSlot = -1;

    static boolean menus_offset = false;
    int mx = (SCREENWIDTH - 320) / 2;
    if (mx > 0 && !menus_offset)
    {
        menus_offset = true;
        MainDef.x += mx;
        MultiDef.x += mx;
        HostDef.x += mx;
        JoinDef.x += mx;
        NewDef.x += mx;
        EpiDef.x += mx;
        OptionsDef.x += mx;
        SoundDef.x += mx;
        LoadDef.x += mx;
        SaveDef.x += mx;
        ReadDef1.x += mx;
        ReadDef2.x += mx;
    }

    // Here we could catch other version dependencies,
    //  like HELP1/2, and four episodes.

  
    switch ( gamemode )
    {
      case commercial:
	// This is used because DOOM 2 had only one HELP
        //  page. I use CREDIT as second page now, but
	//  kept this hack for educational purposes.
	MainMenu[readthis] = MainMenu[quitdoom];
	MainDef.numitems--;
	MainDef.y += 8;
	NewDef.prevMenu = &MainDef;
	ReadDef1.routine = M_DrawReadThis1;
	ReadDef1.x = 330 + mx;
	ReadDef1.y = 165;
	ReadMenu1[0].routine = M_FinishReadThis;
	break;
      case shareware:
	// Episode 2 and 3 are handled,
	//  branching to an ad screen.
      case registered:
	// We need to remove the fourth episode.
	EpiDef.numitems--;
	break;
      case retail:
	// We are fine.
      default:
	break;
    }
    
}

