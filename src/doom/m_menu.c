void M_JoinConnect(int choice)
{
    if (!join_ip_buf[0])
    {
        strcpy(join_ip_buf, "127.0.0.1");
    }

    char ip_copy[64];
    strncpy(ip_copy, join_ip_buf, sizeof(ip_copy) - 1);
    ip_copy[sizeof(ip_copy) - 1] = '\0';

    char* colon = strchr(ip_copy, ':');
    int port = DEFAULT_DOOM_PORT;
    if (colon)
    {
        *colon = '\0';
        int p = atoi(colon + 1);
        if (p > 0 && p < 65536)
            port = p;
    }

    if (!I_Net_JoinGame(ip_copy, port))
    {
        M_StartMessage("FAILED TO CONNECT TO HOST!", NULL, false);
        return;
    }
}

